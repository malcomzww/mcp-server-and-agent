"""Generate the per-topology results table.

Two outputs, deliberately separated -- the same split ``llm-client-kit`` uses,
for the same reason:

- ``results/topologies.md``      committed. Failure rate, token cost and the
                                 paired confidence intervals. All of it is a
                                 pure function of the seed, so CI regenerates
                                 it and fails on any drift.
- ``results/topologies-raw.md``  gitignored. Per-task breakdowns and the
                                 machine that produced them.

Unlike a timing benchmark, *every* number here is machine-independent: there
is no clock in the measurement. The split is kept anyway because the raw file
carries per-task detail that would bloat the committed table without changing
any claim.

The script asserts its own claims. If the supervisor's token premium
disappears, or a topology stops being separable from the baseline, this exits
non-zero rather than quietly writing a different conclusion into the README.

Run:  python scripts/generate_results.py
"""

from __future__ import annotations

import platform
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from llm_eval_harness.stats import is_reportable, paired_delta_ci  # noqa: E402
from llm_eval_harness.types import RunMeta  # noqa: E402

from mcp_server_and_agent.agent import TASKS, AgentConfig, Outcome, RunResult  # noqa: E402
from mcp_server_and_agent.faults import FaultConfig  # noqa: E402
from mcp_server_and_agent.topologies import TOPOLOGIES, run_grid  # noqa: E402

RESULTS = ROOT / "results"
OUT = RESULTS / "topologies.md"          # committed
RAW = RESULTS / "topologies-raw.md"      # gitignored

SEED = 20260825
TRIALS = 100
HARDWARE = "24-core CPU, 32 GB RAM, no GPU"
COMMAND = "python scripts/generate_results.py"

# The headline fault regime. Chosen where the topologies separate: high
# enough that failures happen at a measurable rate inside the step cap, low
# enough that no topology is pinned at a floor or a ceiling. It is NOT
# calibrated against any real model -- calibrating it would need the live
# runs this repo deliberately does not do.
HEADLINE_FAULTS = FaultConfig(
    misselect=0.16,
    bad_args=0.12,
    transient=0.20,
    stall=0.10,
    context_bloat=0.24,
    recovery_skill=0.60,
)
CONFIG = AgentConfig(max_steps=8, context_limit=2000, faults=HEADLINE_FAULTS)

# Fault multipliers for the sensitivity sweep. A ranking that only holds at
# one fault rate is not a finding about topologies.
SCALES = (0.5, 0.75, 1.0, 1.5, 2.0)
SWEEP_TRIALS = 40


def failure_vector(rows: list[RunResult], topology: str) -> list[float]:
    """1.0 for a failed run, 0.0 for a success, in grid order.

    Order matters: the comparison is paired by (task, trial), and
    ``run_grid`` emits topologies in the same task/trial order, so index i of
    two vectors is the same task and the same fault stream.
    """
    return [1.0 if r.failed else 0.0 for r in rows if r.topology == topology]


def token_vector(rows: list[RunResult], topology: str) -> list[float]:
    return [float(r.total_tokens) for r in rows if r.topology == topology]


def summarise(rows: list[RunResult], topology: str) -> dict[str, object]:
    rs = [r for r in rows if r.topology == topology]
    n = len(rs)
    fails = sum(1 for r in rs if r.failed)
    return {
        "n": n,
        "failure_rate": fails / n,
        "tokens": sum(r.total_tokens for r in rs) / n,
        "steps": sum(r.steps for r in rs) / n,
        "handoffs": sum(r.handoffs for r in rs) / n,
        "cost_usd": sum(r.cost_usd for r in rs) / n,
        "modes": Counter(r.outcome.value for r in rs if r.failed),
    }


def write_committed(rows: list[RunResult], sweep: dict[float, dict[str, float]]) -> None:
    meta = RunMeta(
        date=date.today().isoformat(),
        hardware=HARDWARE,
        # Named to be unmistakable. Nobody should read this table and think a
        # real provider was involved.
        model="simulated-scripted-policy (no LLM; see src/.../faults.py)",
        seed=SEED,
        command=COMMAND,
        artifact="results/topologies-raw.md",
    )
    stats = {t: summarise(rows, t) for t in TOPOLOGIES}
    base = stats["single"]

    L: list[str] = []
    add = L.append
    add("# Failure rate and token cost, per topology\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")
    add(meta.provenance_block())
    add("")
    add("> **The agent brain is simulated.** There is no LLM anywhere in this")
    add("> measurement. A deterministic scripted policy executes a plan over the")
    add("> MCP server while a parameterised fault process perturbs its choices.")
    add("> These are failure rates of *topologies under a controlled fault")
    add("> model*, not of any real model in any real deployment.\n")

    add("## Fault model\n")
    add("Per-step probability, drawn independently from a seeded RNG:\n")
    add("| fault | p | what it stands in for |")
    add("|---|---|---|")
    add(f"| `misselect` | {HEADLINE_FAULTS.misselect:.2f} | "
        "two tool descriptions that do not discriminate |")
    add(f"| `bad_args` | {HEADLINE_FAULTS.bad_args:.2f} | a schema the model half-read |")
    add(f"| `transient` | {HEADLINE_FAULTS.transient:.2f} | the network |")
    add(f"| `stall` | {HEADLINE_FAULTS.stall:.2f} | "
        "a model that re-emits its last plan instead of parsing the error |")
    add(f"| `context_bloat` | {HEADLINE_FAULTS.context_bloat:.2f} | "
        "a tool returning a document when asked for a field |")
    add("")
    add(f"`recovery_skill = {HEADLINE_FAULTS.recovery_skill:.2f}` -- the probability")
    add("the policy acts on an error observation that names its own fix. This is")
    add("what \"a better model\" means operationally in this simulation.\n")
    add(f"Controls: `max_steps={CONFIG.max_steps}`, "
        f"`context_limit={CONFIG.context_limit}` tokens, "
        f"`cascade_threshold={CONFIG.cascade_threshold}` consecutive tool errors.\n")

    add("## The table\n")
    add(f"{len(TASKS)} tasks x {TRIALS} trials = **{base['n']} runs per topology**,")
    add("every topology facing the identical fault stream for a given (task, trial).\n")
    add("| topology | failure rate | tokens/run | vs single | steps | handoffs |")
    add("|---|---|---|---|---|---|")
    for t in TOPOLOGIES:
        s = stats[t]
        ratio = s["tokens"] / base["tokens"]
        add(
            f"| `{t}` | **{s['failure_rate']:.1%}** | {s['tokens']:,.0f} | "
            f"{ratio:.2f}x | {s['steps']:.2f} | {s['handoffs']:.2f} |"
        )
    add("")

    # --- the headline question ----------------------------------------
    add("## Does supervisor beat single-agent?\n")
    sup = stats["supervisor"]
    delta, lo, hi = paired_delta_ci(
        failure_vector(rows, "single"), failure_vector(rows, "supervisor"), seed=SEED
    )
    tok_ratio = sup["tokens"] / base["tokens"]
    points = (base["failure_rate"] - sup["failure_rate"]) * 100

    # ASSERTION 1: the supervisor token premium is real and material.
    assert tok_ratio > 1.5, (
        f"supervisor token premium collapsed to {tok_ratio:.2f}x -- headline claim broken"
    )
    # ASSERTION 2: supervisor does reduce failures (a negative delta on the
    # failure vector), and the interval excludes zero. If this breaks, the
    # honest answer changed and the prose below must change with it.
    assert delta < 0, f"supervisor did not reduce failures (delta={delta:+.4f})"
    assert is_reportable(delta, (lo, hi)), (
        f"supervisor-vs-single delta is not separable from zero: "
        f"{delta:+.3f} [{lo:+.3f}, {hi:+.3f}]"
    )

    add("**Yes, but not enough to justify what it costs, and it is dominated.**\n")
    add(
        f"Supervisor cuts the failure rate from {base['failure_rate']:.1%} to "
        f"{sup['failure_rate']:.1%} -- a **{points:.1f} point** reduction. The "
        f"paired bootstrap delta is **{delta:+.3f} [{lo:+.3f}, {hi:+.3f}]** at "
        f"95%, so the improvement is real rather than noise: the interval "
        f"excludes zero. It costs **{tok_ratio:.2f}x the tokens** to get it.\n"
    )
    add(
        f"The reason is structural. A supervisor pays a handoff tax on every "
        f"dispatch -- {sup['handoffs']:.1f} handoffs per run here -- because each "
        f"worker starts cold and must be told the task and the tool list again. "
        f"What it buys is *containment*: a fresh worker context means an error at "
        f"step k does not poison step k+1.\n"
    )

    # The dominance argument: two topologies beat it on both axes.
    for name in ("pipeline", "reflexive"):
        s = stats[name]
        assert s["failure_rate"] < sup["failure_rate"], (
            f"{name} no longer beats supervisor on failure rate"
        )
        assert s["tokens"] < sup["tokens"], f"{name} no longer beats supervisor on tokens"
    add("But containment is available more cheaply. **Both `pipeline` and")
    add("`reflexive` beat `supervisor` on failure rate *and* on tokens** -- the")
    add("script asserts this and exits non-zero if it stops holding:\n")
    add("| topology | failure rate | tokens/run | dominates supervisor? |")
    add("|---|---|---|---|")
    for name in ("supervisor", "pipeline", "reflexive"):
        s = stats[name]
        mark = "--" if name == "supervisor" else "yes, on both axes"
        add(f"| `{name}` | {s['failure_rate']:.1%} | {s['tokens']:,.0f} | {mark} |")
    add("")
    add("So the answer to the repo's question is: supervisor beats single-agent,")
    add("and loses to two simpler things. Paying 1.7x for the third-best outcome")
    add("is the finding.\n")

    # --- the reflexive result -----------------------------------------
    ref = stats["reflexive"]
    r_delta, r_lo, r_hi = paired_delta_ci(
        failure_vector(rows, "single"), failure_vector(rows, "reflexive"), seed=SEED
    )
    assert is_reportable(r_delta, (r_lo, r_hi)), "reflexive delta not separable from zero"
    add("## What actually worked\n")
    add(
        f"`reflexive` -- one agent plus a *single* reflection-and-retry pass -- "
        f"cut failures to **{ref['failure_rate']:.1%}**, a paired delta of "
        f"**{r_delta:+.3f} [{r_lo:+.3f}, {r_hi:+.3f}]** against single-agent, "
        f"for {ref['tokens'] / base['tokens']:.2f}x the tokens.\n"
    )
    add("The retry is not a blind rerun: it inspects the trace, drops the steps")
    add("that already succeeded, and re-attempts only what is outstanding. That is")
    add("why it is cheaper than the supervisor while working better.\n")
    add("The comparison it was built to make: **supervisor and reflexive both add")
    add("tokens, but only one adds a genuinely new capability.** A second agent")
    add("re-does work in a clean context. A second *attempt* uses what the first")
    add("attempt learned. Under this fault model the second is worth more.\n")

    # --- failure modes -------------------------------------------------
    add("## Which failure modes each topology suffers\n")
    add("Counts over all runs, not rates, so the columns sum to the failures above.\n")
    modes = sorted({m for t in TOPOLOGIES for m in stats[t]["modes"]})
    add("| topology | " + " | ".join(f"`{m}`" for m in modes) + " |")
    add("|---" * (len(modes) + 1) + "|")
    for t in TOPOLOGIES:
        counts = stats[t]["modes"]
        add(f"| `{t}` | " + " | ".join(str(counts.get(m, 0)) for m in modes) + " |")
    add("")

    # ASSERTION 3: the containment claim. Fresh worker contexts should mean
    # the supervisor never exhausts context. This is the one place the
    # supervisor is strictly better, and it should be stated as such.
    sup_ctx = stats["supervisor"]["modes"].get(Outcome.CONTEXT_EXHAUSTED.value, 0)
    assert sup_ctx == 0, (
        f"supervisor exhausted context {sup_ctx} times -- the containment claim broke"
    )
    single_cap = stats["single"]["modes"].get(Outcome.STEP_CAP.value, 0)
    pipe_cap = stats["pipeline"]["modes"].get(Outcome.STEP_CAP.value, 0)
    assert pipe_cap < single_cap, "pipeline no longer suppresses step-cap failures"
    add(
        f"The shapes differ more than the totals do. `pipeline` almost eliminates "
        f"step-cap failures ({pipe_cap} versus {single_cap} for single-agent) "
        f"because each stage gets a fresh step budget, so one stalling stage "
        f"cannot consume the whole run's allowance -- but it still cascades as "
        f"often as anyone else, because a failed stage has no re-planner behind "
        f"it. `supervisor` gets a weaker version of the same containment for "
        f"considerably more money.\n"
    )
    add(
        f"At this fault rate **no topology exhausts context** -- the column is "
        f"absent because every count is zero. The `context_bloat` fault fires "
        f"often ({HEADLINE_FAULTS.context_bloat:.0%} of steps) but the "
        f"{CONFIG.context_limit}-token window absorbs it within an 8-step cap. "
        f"Context exhaustion is reproducible here, and the taxonomy carries a "
        f"seed for it, but it needs a tighter window than the headline "
        f"configuration uses. The script asserts the supervisor's count stays "
        f"at zero, since fresh per-worker contexts are the one place its "
        f"architecture is structurally protective.\n"
    )

    # --- sensitivity ---------------------------------------------------
    add("## Does the ranking survive a different fault rate?\n")
    add("All five fault probabilities multiplied by a common factor,")
    add(f"{SWEEP_TRIALS} trials per cell. A ranking that only holds at one fault")
    add("rate is not a finding about topologies.\n")
    add("| scale | " + " | ".join(f"`{t}`" for t in TOPOLOGIES) + " |")
    add("|---" * (len(TOPOLOGIES) + 1) + "|")
    for scale in SCALES:
        cells = " | ".join(f"{sweep[scale][t]:.1%}" for t in TOPOLOGIES)
        add(f"| {scale}x | {cells} |")
    add("")

    # ASSERTION 4: the ordering is stable across the whole sweep.
    for scale in SCALES:
        order = sorted(TOPOLOGIES, key=lambda t: sweep[scale][t])
        assert order[0] == "reflexive", f"at {scale}x, reflexive is not best: {order}"
        assert sweep[scale]["single"] >= sweep[scale]["supervisor"], (
            f"at {scale}x, supervisor lost to single"
        )
        assert sweep[scale]["pipeline"] <= sweep[scale]["supervisor"], (
            f"at {scale}x, pipeline lost to supervisor"
        )
    add("The ordering `reflexive < pipeline < supervisor < single` holds at every")
    add("scale tested, which the script asserts. The *gaps* narrow as faults rise:")
    add("at 2x every topology is failing most of the time, and no amount of")
    add("routing rescues a step that fails 40% of the time. **Topology is a")
    add("second-order effect. Tool reliability is the first-order one** -- which")
    add("is an argument for spending the effort on the tools, not the graph.\n")

    add("## Limitations\n")
    add("- **No LLM was involved.** The policy is scripted and the faults are")
    add("  drawn from a distribution someone chose. The numbers are a property")
    add("  of that fault model, and a different fault model gives different")
    add("  numbers. What transfers is the *shape* of the result, not the values.")
    add("- **The fault rates are uncalibrated.** Nothing here establishes that")
    add("  any real model misselects a tool 16% of the time. Calibrating them")
    add("  needs the live runs this repo deliberately does not do.")
    add("- **Token counts are synthetic**: a fixed charge per step plus")
    add("  `len(text)//4` for observations. Consistent across topologies, so the")
    add("  ratios are meaningful; the dollar figures forecast nobody's bill.")
    add("- **Six tasks, one tool server, one task shape.** All six are")
    add("  search-then-fetch-then-aggregate. A topology that shines on")
    add("  genuinely parallel work would not show it here, and that is exactly")
    add("  the case where a supervisor is supposed to win.")
    add("- **`reflexive` gets one retry; the others get none.** That is the")
    add("  comparison being made on purpose, but it does mean part of its")
    add("  advantage is the retry rather than the reflection.\n")

    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_raw(rows: list[RunResult]) -> None:
    """Per-task detail and the machine. Gitignored."""
    L: list[str] = []
    add = L.append
    add("# Per-topology results: raw detail (not committed)\n")
    add(f"- Date: {date.today().isoformat()}")
    add(f"- Python {platform.python_version()} on {platform.system()} {platform.machine()}")
    add(f"- Seed: {SEED}, trials: {TRIALS}\n")

    add("## Failure rate per (topology, task)\n")
    task_ids = [t.id for t in TASKS]
    add("| topology | " + " | ".join(f"`{t}`" for t in task_ids) + " |")
    add("|---" * (len(task_ids) + 1) + "|")
    for topo in TOPOLOGIES:
        cells = []
        for tid in task_ids:
            rs = [r for r in rows if r.topology == topo and r.task_id == tid]
            cells.append(f"{sum(1 for r in rs if r.failed) / len(rs):.1%}")
        add(f"| `{topo}` | " + " | ".join(cells) + " |")
    add("")

    add("## Mean tokens per (topology, task)\n")
    add("| topology | " + " | ".join(f"`{t}`" for t in task_ids) + " |")
    add("|---" * (len(task_ids) + 1) + "|")
    for topo in TOPOLOGIES:
        cells = []
        for tid in task_ids:
            rs = [r for r in rows if r.topology == topo and r.task_id == tid]
            cells.append(f"{sum(r.total_tokens for r in rs) / len(rs):,.0f}")
        add(f"| `{topo}` | " + " | ".join(cells) + " |")
    add("")

    add("## Simulated spend\n")
    add("At the synthetic price table in `agent.py`. Not a real bill.\n")
    add("| topology | mean USD/run | USD for all runs |")
    add("|---|---|---|")
    for topo in TOPOLOGIES:
        rs = [r for r in rows if r.topology == topo]
        add(f"| `{topo}` | ${sum(r.cost_usd for r in rs) / len(rs):.6f} | "
            f"${sum(r.cost_usd for r in rs):.4f} |")
    add("")

    RAW.write_text("\n".join(L) + "\n", encoding="utf-8")


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    rows = run_grid(TASKS, CONFIG, trials=TRIALS, base_seed=SEED)

    sweep: dict[float, dict[str, float]] = {}
    for scale in SCALES:
        cfg = AgentConfig(
            max_steps=CONFIG.max_steps,
            context_limit=CONFIG.context_limit,
            cascade_threshold=CONFIG.cascade_threshold,
            faults=HEADLINE_FAULTS.scaled(scale),
        )
        srows = run_grid(TASKS, cfg, trials=SWEEP_TRIALS, base_seed=SEED)
        sweep[scale] = {
            t: sum(1 for r in srows if r.topology == t and r.failed)
            / len([r for r in srows if r.topology == t])
            for t in TOPOLOGIES
        }

    write_committed(rows, sweep)
    write_raw(rows)
    print(f"wrote {OUT.name} (committed) and {RAW.name} (gitignored)")
    print("all asserted claims held")


if __name__ == "__main__":
    main()
